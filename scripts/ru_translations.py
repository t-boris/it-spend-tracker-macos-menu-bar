path = pathlib.Path(__file__).resolve().parent.parent / "ITSpendTracker/Resources/Localizable.xcstrings"
catalog = json.loads(path.read_text())
# Strings no longer used in code are dropped.
catalog["strings"] = {k: v for k, v in catalog["strings"].items() if v.get("extractionState") != "stale"}
missing = []
for key, entry in catalog["strings"].items():
    if key not in RU:
        missing.append(key)
        continue
    entry.setdefault("localizations", {})["ru"] = {"stringUnit": {"state": "translated", "value": RU[key]}}
path.write_text(json.dumps(catalog, ensure_ascii=False, indent=2, sort_keys=True) + "\n")
if missing:
    sys.exit("Missing Russian translations:\n" + "\n".join(missing))
print(f"Translated {len(catalog['strings'])} strings")
